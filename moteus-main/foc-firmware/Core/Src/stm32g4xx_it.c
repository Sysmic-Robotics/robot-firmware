/**
  * @brief This function handles EXTI line[15:10] interrupts.
  */
void EXTI15_10_IRQHandler(void)
{
  /* USER CODE BEGIN EXTI15_10_IRQn 0 */
  if (__HAL_GPIO_EXTI_GET_IT(GPIO_PIN_13) != RESET) {
    __HAL_GPIO_EXTI_CLEAR_IT(GPIO_PIN_13);
    TIM2->BDTR &= ~TIM_BDTR_MOE;
    g_drv8323_hw_fault = 1;
  }
  /* USER CODE END EXTI15_10_IRQn 0 */
  HAL_GPIO_EXTI_IRQHandler(GPIO_PIN_13);
  /* USER CODE BEGIN EXTI15_10_IRQn 1 */

  /* USER CODE END EXTI15_10_IRQn 1 */
}

/**
  * @brief This function handles TIM6 global interrupt, DAC1 and DAC3 channel underrun error interrupts.
  */
void TIM6_DAC_IRQHandler(void)
{
  /* USER CODE BEGIN TIM6_DAC_IRQn 0 */
  if (__HAL_TIM_GET_FLAG(&htim6, TIM_FLAG_UPDATE) != RESET) {
    if (__HAL_TIM_GET_IT_SOURCE(&htim6, TIM_IT_UPDATE) != RESET) {
      __HAL_TIM_CLEAR_IT(&htim6, TIM_IT_UPDATE);

      extern Encoder_TypeDef encoder;
      extern FOC_State g_foc;
      extern ServoControl g_servo;
      extern void Encoder_Update(Encoder_TypeDef *enc);
      extern void FOC_RunWithRefs(float th, float vb, float id, float iq);

      Encoder_Update(&encoder);

      const float theta_elec = Encoder_GetElectricalAngle(&encoder);
      const float vbus       = 24.0f;
      const float position_rev = (float)Encoder_GetPosition(&encoder) /
                                 (float)encoder.config.cpr;
      const float velocity_rev_s = Encoder_GetPLLVelocity();

      float id_ref, iq_ref;
      ServoControl_Run(&g_servo,
                       position_rev, velocity_rev_s,
                       theta_elec, vbus,
                       g_foc.id_meas, g_foc.iq_meas,
                       &id_ref, &iq_ref);

      FOC_RunWithRefs(theta_elec, vbus, id_ref, iq_ref);
    }
  }
  /* USER CODE END TIM6_DAC_IRQn 0 */
  HAL_TIM_IRQHandler(&htim6);
  /* USER CODE BEGIN TIM6_DAC_IRQn 1 */

  /* USER CODE END TIM6_DAC_IRQn 1 */
}

